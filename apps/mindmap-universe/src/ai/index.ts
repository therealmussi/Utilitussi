import { resolveAIConfig, isAIConfigured, chatJSON } from './provider'
import { localGenerateMap, localExpand, answerFromKnowledge, type ProposedMap, type ProposedNode } from './localEngine'
import { detectKnowledgeGaps, type KnowledgeGap } from '@/knowledge/discovery'
import type { KnowledgeNode, Connection, Preferences } from '@/types'

export * from './localEngine'

export type SkillEngine = 'remote' | 'local'

const SYSTEM = `You are the knowledge engine of MindMap Universe, a personal knowledge graph app.
Always reply with a single valid JSON object. Be concise and factual. Never invent citations, authors, dates or sources.

Schemas:
- map: {"nodes": [{"title": string, "concept": string, "content": string, "tags": string[], "connectTo": string[], "relation": one of is-related-to|is-part-of|causes|influences|contradicts|depends-on|is-example-of}]}
- gaps: {"gaps": [{"title": string, "concept": string, "reason": string}]}
- expand: {"nodes": [{"title": string, "concept": string, "content": string, "tags": string[], "relation": string}]}`

async function tryRemote<T>(
  prefs: Preferences,
  userPrompt: string,
  fallback: () => T,
  validate: (raw: unknown) => T | null,
): Promise<{ result: T; engine: SkillEngine; error?: string }> {
  const config = resolveAIConfig(prefs)
  if (!isAIConfigured(config)) {
    return { result: fallback(), engine: 'local' }
  }
  try {
    const raw = await chatJSON(config, SYSTEM, userPrompt)
    const validated = validate(raw)
    if (!validated) throw new Error('unexpected AI response shape')
    return { result: validated, engine: 'remote' }
  } catch (err) {
    return { result: fallback(), engine: 'local', error: err instanceof Error ? err.message : String(err) }
  }
}

function errMessage(e: unknown): string {
  return e instanceof Error ? e.message : String(e)
}

export function generateMap(prefs: Preferences, topic: string): Promise<{ result: ProposedMap; engine: SkillEngine; error?: string }> {
  const fallback = () => localGenerateMap(topic)
  return tryRemote<ProposedMap>(
    prefs,
    `Build the skeleton of a knowledge map about "${topic}".
Give 8-16 important concepts (main concepts, subtopics, events, people, disciplines).
"connectTo" must reference an existing node title in this output. Reply with schema "map".`,
    fallback,
    (raw) => {
      const r = raw as { nodes?: unknown }
      if (!Array.isArray(r?.nodes) || r.nodes.length === 0) return null
      const nodes: ProposedNode[] = (r.nodes as unknown[]).flatMap((x) => {
        const o = x as Record<string, unknown>
        if (typeof o?.title !== 'string' || !o.title.trim()) return []
        return [{
          title: o.title,
          kind: 'concept' as const,
          content: typeof o.content === 'string' ? o.content : '',
          tags: Array.isArray(o.tags) ? (o.tags as unknown[]).filter((t): t is string => typeof t === 'string') : [],
          connectTo: Array.isArray(o.connectTo) ? (o.connectTo as unknown[]).filter((t): t is string => typeof t === 'string') : [topic],
          relation: typeof o.relation === 'string' ? o.relation : 'is-related-to',
        }]
      })
      if (nodes.length === 0) return null
      return { topic, nodes, explanation: 'Generated by the configured AI provider. Review before saving.', engine: 'remote' as SkillEngine }
    },
  )
}

export function expandConcept(prefs: Preferences, node: KnowledgeNode, siblings: KnowledgeNode[]): Promise<{ result: ProposedNode[]; engine: SkillEngine; error?: string }> {
  const fallback = () => localExpand(node, siblings)
  return tryRemote<ProposedNode[]>(
    prefs,
    `Expand the concept "${node.title}". Existing description: "${node.content}".
Neighbouring concepts already stored: ${siblings.map((s) => s.title).join('; ') || 'none'}.
Propose up to 5 new nodes and how they relate to "${node.title}". Reply with schema "expand".`,
    fallback,
    (raw) => {
      const r = raw as { nodes?: unknown }
      if (!Array.isArray(r?.nodes)) return null
      const nodes = (r.nodes as unknown[]).flatMap((x) => {
        const o = x as Record<string, unknown>
        if (typeof o?.title !== 'string' || !o.title.trim()) return []
        return [{
          title: o.title,
          kind: 'concept' as const,
          content: typeof o.content === 'string' ? o.content : '',
          tags: Array.isArray(o.tags) ? (o.tags as unknown[]).filter((t): t is string => typeof t === 'string') : [],
          connectTo: [node.title],
          relation: typeof o.relation === 'string' ? o.relation : 'is-related-to',
        }]
      })
      if (nodes.length === 0) return null
      return nodes
    },
  )
}

export function findGaps(prefs: Preferences, nodes: KnowledgeNode[], topic: string): Promise<{ result: KnowledgeGap[]; engine: SkillEngine; error?: string }> {
  const fallback = () => detectKnowledgeGaps(nodes, topic)
  return tryRemote<KnowledgeGap[]>(
    prefs,
    `Here is the list of concepts in the user's graph: ${nodes.map((n) => n.title).join('; ')}.
Topic of interest: "${topic}". Identify up to 6 important missing or implicit concepts, with the reason each is relevant. Reply with schema "gaps".`,
    fallback,
    (raw) => {
      const r = raw as { gaps?: unknown }
      if (!Array.isArray(r?.gaps)) return null
      const gaps = (r.gaps as unknown[]).flatMap((x) => {
        const o = x as Record<string, unknown>
        if (typeof o?.title !== 'string') return []
        return [{
          standaloneTitle: o.title,
          domain: typeof o.domain === 'string' ? o.domain : topic,
          reason: typeof o.reason === 'string' ? o.reason : 'Recommended as an important foundational concept for the topic.',
        }]
      })
      return gaps
    },
  )
}

export async function askUniverse(prefs: Preferences, question: string, nodes: KnowledgeNode[], connections: Connection[]) {
  const config = resolveAIConfig(prefs)
  if (isAIConfigured(config)) {
    try {
      const context = nodes
        .slice(0, 300)
        .map((n) => `- [${n.kind}] ${n.title}: ${n.content.slice(0, 400)}`)
        .join('\n')
      const raw = await chatJSON(
        config,
        SYSTEM,
        `Saved entries from the user's knowledge base:\n${context}\n\nQuestion: "${question}".
Answer preferably using ONLY saved entries; clearly separate what comes from the database, from general knowledge, and what needs external verification. Reply as {"answer": string, "concept": string, "usedNodes": string[]}.`,
      )
      const o = raw as { answer?: unknown; usedNodes?: unknown }
      if (typeof o?.answer !== 'string') throw new Error('unexpected shape')
      const used = Array.isArray(o.usedNodes)
        ? nodes.filter((n) => (o.usedNodes as unknown[]).includes(n.title))
        : []
      return { answer: o.answer, usedNodes: used, engine: 'remote' as SkillEngine }
    } catch (e) {
      const fallback = answerFromKnowledge(question, nodes, connections)
      return { ...fallback, engine: 'local' as SkillEngine, error: errMessage(e) }
    }
  }
  return { ...answerFromKnowledge(question, nodes, connections), engine: 'local' as SkillEngine }
}
